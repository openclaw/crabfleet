func windowsLegacyRuneForKeysym(keysym uint32) (rune, bool) {
	if keysym > 0xffff {
		return 0, false
	}
	low, high := 0, len(windowsLegacyKeysymRunes)
	for low < high {
		middle := low + (high-low)/2
		candidate := uint32(windowsLegacyKeysymRunes[middle].keysym)
		if candidate < keysym {
			low = middle + 1
		} else {
			high = middle
		}
	}
	if low == len(windowsLegacyKeysymRunes) || uint32(windowsLegacyKeysymRunes[low].keysym) != keysym {
		return 0, false
	}
	return windowsLegacyKeysymRunes[low].value, true
}
